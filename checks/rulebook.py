"""规则表：静态检查的唯一来源。

gen-actions.py 用它生成动作 YAML，rules.py 用它执行检查——
两边读同一份表，避免「文档写的」和「实际跑的」不一致。

check 的几种类型：
  regex       扫描 glob 命中的文件，命中数必须 <= max（0 表示不许出现）
  file_present    glob 必须至少命中一个（path 不存在即失败）
  file_absent     这些路径不能出现在 git 跟踪里
  command         执行命令，退出码 0 才算通过
  plist_match     Info.plist 的值必须与 pbxproj 里的构建设置一致
"""

def rule(id, summary, incident, kind, stage, area, domain, check, requires=None):
    return dict(id=id, summary=summary, incident=incident, kind=kind, stage=stage,
                area=area, domain=domain, check=check, requires=requires or [])


def rx(glob, pattern, maxn=0, exclude=None):
    return {"type": "regex", "glob": glob, "pattern": pattern, "max": maxn, "exclude": exclude}


